-- V1: PARAMETROS table matching co.com.practica.fact.entity.Parametro
-- Portable SQL for PostgreSQL (prod). Flyway disabled in dev/test (H2 + Hibernate).

CREATE TABLE PARAMETROS (
    COD_PARAMETRO     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_PARAMETRO  VARCHAR(100) NOT NULL,
    CATEGORIA         VARCHAR(50),
    VALOR             VARCHAR(500),
    DESCRIPCION       VARCHAR(200),
    ESTADO            VARCHAR(1),
    USUARIO_CREACION  VARCHAR(50),
    FECHA_CREACION    TIMESTAMP,
    USUARIO_MOD       VARCHAR(50),
    FECHA_MOD         TIMESTAMP
);

CREATE INDEX IDX_PARAMETROS_ESTADO ON PARAMETROS (ESTADO);
CREATE INDEX IDX_PARAMETROS_NOMBRE ON PARAMETROS (NOMBRE_PARAMETRO);
